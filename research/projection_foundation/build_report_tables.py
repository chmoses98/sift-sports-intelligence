"""Build the cross-sport tables for docs/PROJECTION_FOUNDATION_REPORT.md from each sport's summary.json.

Usage: python research/projection_foundation/build_report_tables.py <summary.json> [...] --out docs/PROJECTION_FOUNDATION_TABLES.md

Every number in the tables is copied from a sport's `sift.projection_foundation.sport_summary.v1`; nothing is computed
or rounded beyond display formatting, so the tables can always be regenerated from the sport repos.
"""
from __future__ import annotations

import argparse
import json

SCHEMA = "sift.projection_foundation.sport_summary.v1"
ORDER = ["NFL", "CFB", "NBA", "MLB", "NHL"]


def f(x, nd=3):
    if x is None:
        return "—"
    if isinstance(x, (int,)) and not isinstance(x, bool):
        return f"{x:,}"
    try:
        return f"{float(x):.{nd}f}"
    except (TypeError, ValueError):
        return str(x)


def ci(d):
    if not d or d.get("mean_diff") is None:
        return "—"
    c = d.get("ci95") or [None, None]
    return f"{d['mean_diff']:+.3f} [{f(c[0])}, {f(c[1])}]"


def calib(m):
    parts = []
    if m.get("cover_80") is not None:
        parts.append(f"80%→{100 * m['cover_80']:.0f}%")
    if m.get("pit_var_ratio") is not None:
        parts.append(f"PITvar {m['pit_var_ratio']:.2f}")
    return ", ".join(parts) or "—"


def family_table(fam) -> str:
    rows = ["| Model | Split | Sample (obs / games) | MAE | RMSE | Bias | CRPS | Calibration | vs baseline (CRPS Δ, 95% CI) | vs incumbent | Verdict |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    for m in fam.get("models", []):
        rows.append("| " + " | ".join([
            str(m.get("model", "")), str(m.get("split", "")),
            f"{f(m.get('n_obs'))} / {f(m.get('n_clusters'))}",
            f(m.get("mae")), f(m.get("rmse")), f(m.get("bias")), f(m.get("crps")), calib(m),
            ci(m.get("vs_baseline")), ci(m.get("vs_incumbent")) if m.get("vs_incumbent") else "n/a",
            str(m.get("verdict", "")),
        ]) + " |")
    h = fam.get("holdout") or {}
    if h:
        rows.append("| **" + str(h.get("model", fam.get("best_model", ""))) + "** | **holdout** | "
                    + f"{f(h.get('n_obs'))} / {f(h.get('n_clusters'))} | {f(h.get('mae'))} | {f(h.get('rmse'))} | {f(h.get('bias'))} | "
                    + f"{f(h.get('crps'))} | {calib(h)} | {ci(h.get('vs_baseline'))} | {ci(h.get('vs_incumbent')) if h.get('vs_incumbent') else 'n/a'} | frozen |")
    return "\n".join(rows) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("summaries", nargs="+")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    docs = []
    for p in a.summaries:
        d = json.load(open(p))
        if d.get("schema") != SCHEMA:
            raise SystemExit(f"{p}: unexpected schema {d.get('schema')}")
        docs.append(d)
    docs.sort(key=lambda d: ORDER.index(d["sport"]) if d["sport"] in ORDER else 99)

    out = ["# Projection Foundation — generated tables", "",
           "Generated by `research/projection_foundation/build_report_tables.py` from each sport repo's "
           "`research/projection_foundation/results/summary.json`. Bias = mean(projection − actual): positive = projects too high. "
           "CRPS is the whole-distribution error (lower is better). Calibration: share of outcomes inside the 80% range "
           "(target 80%) and PIT variance ratio (1.00 = calibrated, >1 = ranges too narrow/overconfident, <1 = too wide). "
           "Δ columns are game-clustered bootstrap differences; negative = better than the comparator.", ""]

    out += ["## Production-readiness scorecard", "", "| Sport | Family | Readiness | Best model | Why |", "|---|---|---|---|---|"]
    for d in docs:
        for fam in d.get("families", []):
            out.append(f"| {d['sport']} | {fam['family']} | **{fam.get('readiness', '')}** | {fam.get('best_model', '')} | {fam.get('readiness_reason', '')} |")
    out.append("")

    for d in docs:
        out += [f"## {d['sport']}", "", f"Splits: " + "; ".join(f"**{k}** {v}" for k, v in (d.get("splits") or {}).items()),
                f"  Code: `{d.get('code_sha', '')[:10]}`, pf_core {d.get('pf_core_version', '')}, generated {d.get('generated_utc', '')}.", ""]
        inv = d.get("inventory") or []
        if inv:
            out += ["### Data inventory", "", "| Dataset | Seasons | Rows | Point-in-time class | Notes |", "|---|---|---|---|---|"]
            for r in inv:
                out.append(f"| {r.get('dataset', '')} | {r.get('seasons', '')} | {f(r.get('rows'))} | {r.get('pit_class', '')} | {r.get('notes', '')} |")
            out.append("")
        for fam in d.get("families", []):
            out += [f"### {d['sport']} · {fam['family']} ({fam.get('unit', '')}; population: {fam.get('population', '')})", "",
                    family_table(fam)]
        g = d.get("gate") or {}
        if g:
            out += ["### Quality gate on backtest projections", "", "```json", json.dumps(g, indent=1)[:3000], "```", ""]
    open(a.out, "w").write("\n".join(out) + "\n")
    print(f"wrote {a.out} ({len(docs)} sports)")


if __name__ == "__main__":
    main()
