#!/usr/bin/env node
// Write the live-quote feed into <outdir> (the live-quotes workflow force-pushes it to the
// `live-quotes` branch). Read-only: Kalshi public market data + the sport publication.
//   node scripts/publish-live-quotes.mjs out/live-quotes
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { buildFiles, makeGet, publicationGames, sweep } from './live-quotes/lib.mjs';

// Sports whose publication Sift maps to Kalshi. One line per sport; the feed format is sport-agnostic.
const SPORTS = [
  { code: 'NFL', rawBase: 'https://raw.githubusercontent.com/chmoses98/nfl-edge-finder/handicap-reports/app/latest' },
  { code: 'NHL', rawBase: 'https://raw.githubusercontent.com/chmoses98/NHL-edge-finder/data-archive/app/latest' },
];

const out = process.argv[2] ?? 'out/live-quotes';
const log = (s) => console.log(s);
const { get, count } = makeGet({ log });
const games = [];
for (const s of SPORTS) {
  const g = await publicationGames(s.rawBase, get);
  log(`${s.code}: ${g.length} upcoming game keys from the publication`);
  games.push(...g);
}
const { byKey, errors } = await sweep(games, get, { log });
const total = [...byKey.values()].reduce((a, m) => a + m.size, 0);
const files = buildFiles(games, byKey, { generatedAt: new Date().toISOString().replace(/\.\d{3}Z$/, 'Z'), sports: SPORTS.map((s) => s.code), errors, requests: count() });
for (const [rel, doc] of files) {
  const p = join(out, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, JSON.stringify(doc));
}
writeFileSync(join(out, 'README.md'), '# Sift live-quote feed\n\nGenerated by `.github/workflows/live-quotes.yml` from Kalshi public market data (read-only). Force-pushed; no history is kept.\n');
log(`wrote ${files.size} files, ${total} markets, ${count()} requests, ${errors.length} errors`);
if (games.length && total === 0) {
  console.error('no market could be read from Kalshi; not publishing an empty feed');
  process.exit(1);
}
